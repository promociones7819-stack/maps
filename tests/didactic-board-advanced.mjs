import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

const browser=await chromium.launch();
try {
 const page=await browser.newPage({viewport:{width:1440,height:960}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 page.setDefaultTimeout(20000);
 await page.addInitScript(()=>localStorage.setItem('traza-bizkaia-language','es'));
 await page.goto('http://localhost:5173');
 await page.getByRole('button',{name:'Entrar en la aplicación'}).click();
 await page.getByRole('button',{name:'Enfocar',exact:true}).click();
 const open=page.getByRole('button',{name:'Pizarra didáctica',exact:false});
 await page.waitForFunction(()=>!document.querySelector('.pizarra-launch').disabled);
 await open.click();
 const board=page.getByRole('dialog',{name:'Pizarra didáctica'});
 await board.getByRole('status').filter({hasText:'Señala sobre el mapa'}).waitFor();
 const map=board.locator('.board-map');
 const at=async(x,y)=>{const b=await map.boundingBox();await page.mouse.click(b.x+b.width*x,b.y+b.height*y);};
 const drag=async(x1,y1,x2,y2)=>{const b=await map.boundingBox();await page.mouse.move(b.x+b.width*x1,b.y+b.height*y1);await page.mouse.down();await page.mouse.move(b.x+b.width*x2,b.y+b.height*y2,{steps:10});await page.mouse.up();};
 await board.getByRole('button',{name:'Vehículos',exact:true}).click();
 await board.getByRole('button',{name:'Vehículo',exact:true}).click();
 await at(.45,.62);
 const car=board.getByRole('button',{name:'Vehículo A'});
 await car.waitFor();
 await car.click();
 await board.getByRole('button',{name:'Dibujar recorrido'}).click();
 await at(.45,.62);await at(.55,.65);await at(.6,.55);
 await board.getByRole('button',{name:'Terminar trazo'}).click();
 const slider=board.getByRole('slider',{name:'Progreso de animación'});
 await slider.fill('50');
 assert.equal(await slider.inputValue(),'50');
 await board.getByRole('button',{name:'Dibujar',exact:true}).click();
 await board.getByRole('button',{name:'Rotulador',exact:true}).click();
 await drag(.3,.55,.35,.58);
 assert.ok(parseInt(await board.locator('.board-count').textContent(),10)>=2);
 await board.getByRole('button',{name:'Explicar',exact:true}).click();
 await board.getByLabel('Pregunta (opcional)').fill('¿Quién tiene prioridad?');
 await board.getByLabel('Respuesta',{exact:true}).fill('Depende de la señalización real.');
 await board.getByRole('button',{name:'Añadir escena actual'}).click();
 await board.getByRole('button',{name:'Presentar',exact:true}).click();
 await board.getByRole('button',{name:'Iniciar presentación'}).click();
 await board.getByText('¿Quién tiene prioridad?').waitFor();
 await board.getByRole('button',{name:'Mostrar respuesta'}).click();
 await board.getByText('Depende de la señalización real.').waitFor();
 await board.getByRole('button',{name:'Finalizar',exact:true}).click();
 await board.getByRole('button',{name:'Guardar / Abrir / Exportar'}).click();
 await board.getByLabel('Nombre',{exact:true}).fill('Caso 01');
 await board.getByRole('button',{name:'Guardar',exact:true}).click();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('traza-bizkaia-didactic-boards-v1')));
 assert.equal(saved[0].name,'Caso 01');
 assert.equal(saved[0].scenes.length,1);
 assert.ok(saved[0].items.some(i=>i.type==='vehicle'));
 const pngWait=page.waitForEvent('download');
 await board.getByRole('button',{name:'PNG',exact:true}).click();
 const png=await pngWait;
 assert.match(png.suggestedFilename(),/\.png$/);
 const pngBytes=await readFile(await png.path());
 assert.equal(pngBytes.subarray(1,4).toString('ascii'),'PNG');
 const pdfWait=page.waitForEvent('download');
 await board.getByRole('button',{name:'PDF',exact:true}).click();
 const pdf=await pdfWait;
 const pdfBytes=await readFile(await pdf.path());
 assert.equal(pdfBytes.subarray(0,5).toString('ascii'),'%PDF-');
 assert.deepEqual(errors,[]);
 console.log('didactic-board-advanced PASS: place vehicle, draw path, animate slider, freehand, scene presentation, save independently.');
} finally {await browser.close();}
